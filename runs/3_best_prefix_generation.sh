#!/bin/bash
# =============================================================================
# Stage 3a — Best-of-N Generation (N=8, Train + Valid Splits)
# =============================================================================
# Reads the ranked CSV from Stage 2 and, for each user, selects the history
# item with the lowest retrieval rank (= best anchor) via --ranked_csv.
# Then generates N=8 diverse trajectories at temperature=1.0 to explore
# varied phrasings anchored to that best item.
#
# Input  : data_processed/{dataset}_gemma-3-1b-it_{split}_key_selection_prefix_ranked.csv
#          (generated by Stage 2)
# Output : data_processed/{dataset}_gemma-3-1b-it_{split}_key_selection_best_from_*_ranked.csv
#          Contains 8 trajectory candidates per user.
#          Used by Stage 3b for re-evaluation.
# =============================================================================

DEVICE=0
MODEL_NAME="google/gemma-3-1b-it"
MODEL_DIR="gemma-3-1b-it"
EMB_TYPE="item_preference_1024_gemma-3-4b-it"
EMB_MODEL="mixedbread-ai/mxbai-embed-large-v1"

SPLITS=(train valid)
DATASETS=(beauty sports toys)
N_SAMPLES=8         # number of diverse trajectories to sample per user
TEMPERATURE=1.0     # high temperature to encourage diverse phrasings

for dataset in "${DATASETS[@]}"; do
for split in "${SPLITS[@]}"; do

    RANKED_CSV="data_processed/${dataset}_${MODEL_DIR}_${split}_key_selection_prefix_ranked.csv"
    if [ ! -f "$RANKED_CSV" ]; then
        echo "⚠️  Skip (not found): $RANKED_CSV"
        continue
    fi

    echo "▶ [best_postfix x${N_SAMPLES} samples] ${dataset} / ${split}"

    CUDA_VISIBLE_DEVICES=$DEVICE python3 src/generate_key_selection.py \
        --data_name   "$dataset" \
        --split       "$split" \
        --model_name  "$MODEL_NAME" \
        --temperature $TEMPERATURE \
        --gpu_memory_utilization 0.95 \
        --ranked_csv  "$RANKED_CSV" \
        --n_samples   $N_SAMPLES

    echo "✓ Done: ${dataset} / ${split}  (${N_SAMPLES} samples)"
    echo "──────────────────────────────────────────────────────"

    CSV="data_processed/${dataset}_${MODEL_DIR}_${SPLIT}_key_selection_best_from_${dataset}_${MODEL_DIR}_${SPLIT}_key_selection_prefix_ranked.csv"
    [ ! -f "$CSV" ] && echo "⚠️  Skip (not found): $CSV" && continue
    CUDA_VISIBLE_DEVICES=$DEVICE python3 src/eval_key_selection.py \
        --input_csv "$CSV" \
        --data_name "$dataset" \
        --split "$SPLIT" \
        --emb_type "$EMB_TYPE" \
        --emb_model_name "$EMB_MODEL" \
        --use_sentence_transformers
done
done

